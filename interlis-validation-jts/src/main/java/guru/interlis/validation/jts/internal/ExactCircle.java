package guru.interlis.validation.jts.internal;

import guru.interlis.validation.jts.internal.CurveSegment.Point;

import java.math.BigDecimal;
import java.math.BigInteger;

/** A circle centre represented as a rational position plus a vector times one square root. */
record ExactCircle(Rational x, Rational y, Rational offsetX, Rational offsetY,
                   Rational radicand, Rational radiusSquared) {
    private static final Rational TWO = Rational.of(2);
    private static final Rational FOUR = Rational.of(4);

    static ExactCircle through(Point start, Point support, Point end) {
        var startX = Rational.of(start.exactX());
        var startY = Rational.of(start.exactY());
        var ax = Rational.of(support.exactX().subtract(start.exactX()));
        var ay = Rational.of(support.exactY().subtract(start.exactY()));
        var bx = Rational.of(end.exactX().subtract(start.exactX()));
        var by = Rational.of(end.exactY().subtract(start.exactY()));
        var aLength = ax.square().add(ay.square());
        var bLength = bx.square().add(by.square());
        var denominator = ax.multiply(by).subtract(ay.multiply(bx)).multiply(TWO);
        var dx = aLength.multiply(by).subtract(bLength.multiply(ay)).divide(denominator);
        var dy = ax.multiply(bLength).subtract(bx.multiply(aLength)).divide(denominator);
        return rational(startX.add(dx), startY.add(dy), dx.square().add(dy.square()));
    }

    static Rational chordSquared(Point start, Point end) {
        var dx = Rational.of(end.exactX().subtract(start.exactX()));
        var dy = Rational.of(end.exactY().subtract(start.exactY()));
        return dx.square().add(dy.square());
    }

    static ExactCircle fromRadius(Point start, Point end, Rational radiusSquared, int side) {
        var dx = Rational.of(end.exactX().subtract(start.exactX()));
        var dy = Rational.of(end.exactY().subtract(start.exactY()));
        var chordSquared = dx.square().add(dy.square());
        var middleX = Rational.of(start.exactX().add(end.exactX())).divide(TWO);
        var middleY = Rational.of(start.exactY().add(end.exactY())).divide(TWO);
        var radicand = radiusSquared.divide(chordSquared).subtract(Rational.ONE.divide(FOUR));
        var offsetX = side > 0 ? dy.negate() : dy;
        var offsetY = side > 0 ? dx : dx.negate();
        var squareRoot = radicand.rationalSquareRoot();
        if (squareRoot != null) {
            return rational(middleX.add(offsetX.multiply(squareRoot)), middleY.add(offsetY.multiply(squareRoot)),
                    radiusSquared);
        }
        return new ExactCircle(middleX, middleY, offsetX, offsetY, radicand, radiusSquared);
    }

    private static ExactCircle rational(Rational x, Rational y, Rational radiusSquared) {
        return new ExactCircle(x, y, Rational.ZERO, Rational.ZERO, Rational.ZERO, radiusSquared);
    }

    Interval centreX(int digits) {
        return position(x, offsetX, digits);
    }

    Interval centreY(int digits) {
        return position(y, offsetY, digits);
    }

    private Interval position(Rational base, Rational offset, int digits) {
        var result = base.interval(digits);
        return offset.signum() == 0 ? result : result.add(offset.interval(digits).multiply(radicand.interval(digits).sqrt()));
    }

    boolean sameCircle(ExactCircle other) {
        return radiusSquared.equals(other.radiusSquared) && sameCentre(other);
    }

    boolean sameCentre(ExactCircle other) {
        return sameOrdinate(x, offsetX, other.x, other.offsetX, other.radicand)
                && sameOrdinate(y, offsetY, other.y, other.offsetY, other.radicand);
    }

    int circleDiscriminant(ExactCircle other) {
        var dxBound = centreX().subtract(other.centreX());
        var dyBound = centreY().subtract(other.centreY());
        var distanceBound = dxBound.square().add(dyBound.square());
        int filtered = distanceBound.multiply(radiusSquared.interval()).multiply(DoubleInterval.around(4))
                .subtract(distanceBound.add(radiusSquared.interval()).subtract(other.radiusSquared.interval()).square())
                .sign();
        if (filtered != Interval.OVERLAPS_ZERO) {
            return filtered;
        }
        if (radicand.signum() == 0 && other.radicand.signum() == 0) {
            var distanceSquared = x.subtract(other.x).square().add(y.subtract(other.y).square());
            var numerator = distanceSquared.add(radiusSquared).subtract(other.radiusSquared);
            return FOUR.multiply(radiusSquared).multiply(distanceSquared).subtract(numerator.square()).signum();
        }
        // The discriminant stays in the field generated by the two exact centre radicals.
        var dx = centreDifference(x, offsetX, other.x, other.offsetX, other.radicand);
        var dy = centreDifference(y, offsetY, other.y, other.offsetY, other.radicand);
        var distanceSquared = dx.square().add(dy.square());
        var numerator = distanceSquared.add(radiusSquared.subtract(other.radiusSquared));
        return distanceSquared.multiply(FOUR.multiply(radiusSquared)).subtract(numerator.square()).signum();
    }

    private RadicalPair centreDifference(Rational base, Rational offset, Rational otherBase,
                                         Rational otherOffset, Rational otherRadicand) {
        return new RadicalPair(new Radical(base.subtract(otherBase), offset, radicand),
                new Radical(otherOffset.negate(), Rational.ZERO, radicand), otherRadicand);
    }

    private boolean sameOrdinate(Rational base, Rational offset, Rational otherBase, Rational otherOffset,
                                 Rational otherRadicand) {
        // A sum of a rational and a nonrational signed square root has a unique decomposition.
        return base.equals(otherBase) && offset.signum() == otherOffset.signum()
                && offset.square().multiply(radicand).equals(otherOffset.square().multiply(otherRadicand));
    }

    int pointSide(Point point) {
        var dxBound = DoubleInterval.around(point.x()).subtract(centreX());
        var dyBound = DoubleInterval.around(point.y()).subtract(centreY());
        int filtered = dxBound.square().add(dyBound.square()).subtract(radiusSquared.interval()).sign();
        if (filtered != Interval.OVERLAPS_ZERO) {
            return filtered;
        }
        var dx = Rational.of(point.exactX()).subtract(x);
        var dy = Rational.of(point.exactY()).subtract(y);
        var constant = dx.square().add(dy.square())
                .add(offsetX.square().add(offsetY.square()).multiply(radicand)).subtract(radiusSquared);
        var coefficient = dx.multiply(offsetX).add(dy.multiply(offsetY)).multiply(TWO).negate();
        return sign(constant, coefficient);
    }

    int centreSide(Point start, Point end) {
        var dx = Rational.of(end.exactX().subtract(start.exactX()));
        var dy = Rational.of(end.exactY().subtract(start.exactY()));
        var constant = dx.multiply(y.subtract(Rational.of(start.exactY())))
                .subtract(dy.multiply(x.subtract(Rational.of(start.exactX()))));
        return sign(constant, dx.multiply(offsetY).subtract(dy.multiply(offsetX)));
    }

    int lineDiscriminant(Point start, Point end) {
        var sx = DoubleInterval.around(start.x());
        var sy = DoubleInterval.around(start.y());
        var dirX = DoubleInterval.around(end.x()).subtract(sx);
        var dirY = DoubleInterval.around(end.y()).subtract(sy);
        var px = sx.subtract(centreX());
        var py = sy.subtract(centreY());
        var determinant = dirX.multiply(py).subtract(dirY.multiply(px));
        int filtered = radiusSquared.interval().multiply(dirX.square().add(dirY.square()))
                .subtract(determinant.square()).sign();
        if (filtered != Interval.OVERLAPS_ZERO) {
            return filtered;
        }
        var dx = Rational.of(end.exactX().subtract(start.exactX()));
        var dy = Rational.of(end.exactY().subtract(start.exactY()));
        var ox = Rational.of(start.exactX()).subtract(x);
        var oy = Rational.of(start.exactY()).subtract(y);
        var cross = dx.multiply(oy).subtract(dy.multiply(ox));
        var offset = dy.multiply(offsetX).subtract(dx.multiply(offsetY));
        var constant = radiusSquared.multiply(dx.square().add(dy.square()))
                .subtract(cross.square()).subtract(offset.square().multiply(radicand));
        return sign(constant, cross.multiply(offset).multiply(TWO).negate());
    }

    private int sign(Rational constant, Rational coefficient) {
        return radicalSign(constant, coefficient, radicand);
    }

    private static int radicalSign(Rational constant, Rational coefficient, Rational radicand) {
        int a = constant.signum();
        int b = coefficient.signum();
        if (b == 0 || radicand.signum() == 0) {
            return a;
        }
        if (a == 0 || a == b) {
            return b;
        }
        return a * constant.square().compareTo(coefficient.square().multiply(radicand));
    }

    private DoubleInterval centreX() {
        return offsetX.signum() == 0 ? x.interval() : x.interval().add(offsetX.interval().multiply(radicand.interval().sqrt()));
    }

    private DoubleInterval centreY() {
        return offsetY.signum() == 0 ? y.interval() : y.interval().add(offsetY.interval().multiply(radicand.interval().sqrt()));
    }

    private record Radical(Rational base, Rational coefficient, Rational root) {
        Radical add(Radical other) {
            return new Radical(base.add(other.base), coefficient.add(other.coefficient), root);
        }

        Radical add(Rational other) {
            return new Radical(base.add(other), coefficient, root);
        }

        Radical negate() {
            return new Radical(base.negate(), coefficient.negate(), root);
        }

        Radical multiply(Radical other) {
            return new Radical(base.multiply(other.base).add(coefficient.multiply(other.coefficient).multiply(root)),
                    base.multiply(other.coefficient).add(coefficient.multiply(other.base)), root);
        }

        Radical multiply(Rational other) {
            return new Radical(base.multiply(other), coefficient.multiply(other), root);
        }

        Radical square() {
            return multiply(this);
        }

        int signum() {
            return radicalSign(base, coefficient, root);
        }
    }

    private record RadicalPair(Radical base, Radical coefficient, Rational root) {
        RadicalPair add(RadicalPair other) {
            return new RadicalPair(base.add(other.base), coefficient.add(other.coefficient), root);
        }

        RadicalPair add(Rational other) {
            return new RadicalPair(base.add(other), coefficient, root);
        }

        RadicalPair subtract(RadicalPair other) {
            return new RadicalPair(base.add(other.base.negate()), coefficient.add(other.coefficient.negate()), root);
        }

        RadicalPair multiply(Rational other) {
            return new RadicalPair(base.multiply(other), coefficient.multiply(other), root);
        }

        RadicalPair square() {
            return new RadicalPair(base.square().add(coefficient.square().multiply(root)),
                    base.multiply(coefficient).multiply(TWO), root);
        }

        int signum() {
            int a = base.signum();
            int b = coefficient.signum();
            if (root.signum() == 0 || b == 0) {
                return a;
            }
            if (a == 0 || a == b) {
                return b;
            }
            return a * base.square().add(coefficient.square().multiply(root).negate()).signum();
        }
    }

    record Rational(BigInteger numerator, BigInteger denominator) implements Comparable<Rational> {
        static final Rational ZERO = of(0);
        static final Rational ONE = of(1);

        Rational {
            if (denominator.signum() == 0) {
                throw new ArithmeticException("Zero rational denominator");
            }
            var divisor = numerator.gcd(denominator);
            if (denominator.signum() < 0) {
                divisor = divisor.negate();
            }
            numerator = numerator.divide(divisor);
            denominator = denominator.divide(divisor);
        }

        static Rational of(long value) {
            return new Rational(BigInteger.valueOf(value), BigInteger.ONE);
        }

        static Rational of(BigDecimal value) {
            int scale = value.scale();
            return scale >= 0
                    ? new Rational(value.unscaledValue(), BigInteger.TEN.pow(scale))
                    : new Rational(value.unscaledValue().multiply(BigInteger.TEN.pow(-scale)), BigInteger.ONE);
        }

        int signum() {
            return numerator.signum();
        }

        Rational add(Rational other) {
            return new Rational(numerator.multiply(other.denominator).add(other.numerator.multiply(denominator)),
                    denominator.multiply(other.denominator));
        }

        Rational subtract(Rational other) {
            return add(other.negate());
        }

        Rational negate() {
            return new Rational(numerator.negate(), denominator);
        }

        Rational multiply(Rational other) {
            return new Rational(numerator.multiply(other.numerator), denominator.multiply(other.denominator));
        }

        Rational divide(Rational other) {
            return new Rational(numerator.multiply(other.denominator), denominator.multiply(other.numerator));
        }

        Rational square() {
            return multiply(this);
        }

        Rational rationalSquareRoot() {
            var top = numerator.sqrtAndRemainder();
            var bottom = denominator.sqrtAndRemainder();
            return top[1].signum() == 0 && bottom[1].signum() == 0 ? new Rational(top[0], bottom[0]) : null;
        }

        Interval interval(int digits) {
            return Interval.ratio(new BigDecimal(numerator), new BigDecimal(denominator), digits);
        }

        DoubleInterval interval() {
            return DoubleInterval.around(numerator.doubleValue()).divide(DoubleInterval.around(denominator.doubleValue()));
        }

        @Override public int compareTo(Rational other) {
            return numerator.multiply(other.denominator).compareTo(other.numerator.multiply(denominator));
        }
    }
}
