package guru.interlis.diagnostics;

/** Catalog-declared argument wire kind. */
public enum ArgumentKind {
    /** The {@code TEXT} constant. */
    TEXT,
    /** The {@code IDENTIFIER} constant. */
    IDENTIFIER,
    /** The {@code TOKEN} constant. */
    TOKEN,
    /** The {@code INTEGER} constant. */
    INTEGER,
    /** The {@code DECIMAL} constant. */
    DECIMAL,
    /** The {@code TYPE_NAME} constant. */
    TYPE_NAME,
    /** The {@code IDENTIFIER_LIST} constant. */
    IDENTIFIER_LIST
}
